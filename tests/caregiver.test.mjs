import assert from "node:assert/strict"
import test from "node:test"
import { CaregiverCommBridge, careCategories } from "../Assets/Scripts/room/CaregiverCommBridge.ts"

test("requires explicit acknowledgment and completion after delivery", () => {
  const bridge = new CaregiverCommBridge()
  assert.equal(bridge.request("Water", 1), true)
  assert.equal(bridge.state, "Pending")
  assert.equal(bridge.acknowledge(1), false)
  assert.equal(bridge.complete(1), false)
  assert.equal(bridge.update(0.125, 1.125), false)
  assert.equal(bridge.state, "Pending")
  assert.equal(bridge.update(0.125, 1.25), true)
  assert.equal(bridge.state, "Delivered")
  assert.equal(bridge.update(10, 11.25), false)
  assert.equal(bridge.state, "Delivered")
  assert.equal(bridge.changedAt, 1.25)
  assert.equal(bridge.complete(11.25), false)

  assert.equal(bridge.acknowledge(12), true)
  assert.equal(bridge.acknowledge(13), false)
  assert.equal(bridge.state, "Acknowledged")
  assert.equal(bridge.changedAt, 12)
  assert.equal(bridge.complete(14), true)
  assert.equal(bridge.complete(15), false)
  assert.equal(bridge.state, "Completed")
  assert.equal(bridge.category, "Water")
  assert.equal(bridge.requestedAt, 1)
  assert.equal(bridge.changedAt, 14)
})

test("an offline request stays failed through reconnect until explicit retry", () => {
  const bridge = new CaregiverCommBridge()
  assert.equal(bridge.setOnline(false, 1), true)
  assert.equal(bridge.setOnline(false, 1), false)
  assert.equal(bridge.request("Reposition", 2), true)
  assert.equal(bridge.state, "Delivery failed")
  assert.equal(bridge.changedAt, 2)
  assert.equal(bridge.acknowledge(3), false)
  assert.equal(bridge.update(5, 7), false)
  assert.equal(bridge.retry(8), false)
  assert.equal(bridge.state, "Delivery failed")
  assert.equal(bridge.setOnline(true, 9), true)
  assert.equal(bridge.update(5, 14), false)
  assert.equal(bridge.state, "Delivery failed")

  assert.equal(bridge.retry(15), true)
  assert.equal(bridge.state, "Pending")
  assert.equal(bridge.category, "Reposition")
  assert.equal(bridge.requestedAt, 2)
  assert.equal(bridge.changedAt, 15)
  assert.equal(bridge.update(0.25, 15.25), true)
  assert.equal(bridge.state, "Delivered")
})

test("disconnect cancels a pending delivery and retry starts a fresh delivery", () => {
  const bridge = new CaregiverCommBridge()
  assert.equal(bridge.request("Temperature", 0), true)
  assert.equal(bridge.update(0.125, 0.125), false)
  assert.equal(bridge.setOnline(false, 0.125), true)
  assert.equal(bridge.state, "Delivery failed")
  assert.equal(bridge.setOnline(true, 1), true)
  assert.equal(bridge.retry(1), true)
  assert.equal(bridge.update(0.125, 1.125), false)
  assert.equal(bridge.state, "Pending")
  assert.equal(bridge.update(0.125, 1.25), true)
  assert.equal(bridge.setOnline(false, 2), true)
  assert.equal(bridge.state, "Delivered")
})

test("accepts all four categories and rejects new requests while one is active", () => {
  const bridge = new CaregiverCommBridge()
  assert.deepEqual(careCategories, ["Water", "Reposition", "Temperature", "Assistance"])

  for (const [index, category] of careCategories.entries()) {
    const now = index * 5
    assert.equal(bridge.request(category, now), true)
    assert.equal(bridge.request(category, now), false)
    assert.equal(bridge.retry(now), false)
    assert.equal(bridge.update(0.25, now + 1), true)
    assert.equal(bridge.request("Assistance", now + 1), false)
    assert.equal(bridge.acknowledge(now + 2), true)
    assert.equal(bridge.request("Assistance", now + 2), false)
    assert.equal(bridge.complete(now + 3), true)
    assert.equal(bridge.category, category)
  }
})

test("reset clears pending progress, connection simulation and timestamps", () => {
  const bridge = new CaregiverCommBridge()
  assert.equal(bridge.request("Assistance", 0), true)
  assert.equal(bridge.update(0.125, 0.125), false)
  assert.equal(bridge.setOnline(false, 0.125), true)
  bridge.reset()

  assert.equal(bridge.state, "Idle")
  assert.equal(bridge.category, null)
  assert.equal(bridge.online, true)
  assert.equal(bridge.changedAt, null)
  assert.equal(bridge.requestedAt, null)
  assert.equal(bridge.update(10, 1), false)
  assert.equal(bridge.request("Water", 1), true)
  assert.equal(bridge.update(0.125, 1.125), false)
  assert.equal(bridge.state, "Pending")
})

test("rejects invalid inputs without changing state or accumulating delivery time", () => {
  assert.throws(() => new CaregiverCommBridge(0), RangeError)
  assert.throws(() => new CaregiverCommBridge(Infinity), RangeError)
  const bridge = new CaregiverCommBridge()
  assert.equal(bridge.request("Unknown", 0), false)
  assert.equal(bridge.request("Water", Infinity), false)
  assert.equal(bridge.state, "Idle")
  assert.equal(bridge.request("Water", 1), true)
  assert.equal(bridge.update(Infinity, 2), false)
  assert.equal(bridge.update(-1, 2), false)
  assert.equal(bridge.update(0.25, 0), false)
  assert.equal(bridge.update(0.125, 2), false)
  assert.equal(bridge.state, "Pending")
})
